// Build-time font subsetting. Run `npm run build:fonts` if the font or the
// charsets change; the output (src/font-subsets.ts) is committed.
//
// Uses HarfBuzz (via subset-font) and writes WOFF2. The earlier fontkit
// subsets had no cmap table, so browsers rejected them and every SVG fell back
// to Arial (June to November 2026). Check a change by opening an SVG in Chrome.
import subsetFont from "subset-font";
import { readFileSync, writeFileSync } from "fs";

const NUMERIC_CHARS = "0123456789 x"; // default "W x H" dimension text
const ASCII = Array.from({ length: 95 }, (_, i) => String.fromCharCode(32 + i)).join("");
const font = readFileSync("AauxOffice-Bold.ttf");

// Every character the font has a glyph for (read from its cmap table). Used
// for the "full" subset, so accented letters and curly quotes show in the
// brand font instead of falling back to Arial.
function fontCharacters(b) {
  const tables = b.readUInt16BE(4);
  let cmap = 0;
  for (let i = 0; i < tables; i++) {
    const o = 12 + i * 16;
    if (b.toString("latin1", o, o + 4) === "cmap") cmap = b.readUInt32BE(o + 8);
  }
  const cps = new Set();
  for (let i = 0; i < b.readUInt16BE(cmap + 2); i++) {
    const t = cmap + b.readUInt32BE(cmap + 8 + i * 8);
    if (b.readUInt16BE(t) !== 4) continue;
    const segX2 = b.readUInt16BE(t + 6);
    const ends = t + 14, starts = ends + segX2 + 2, deltas = starts + segX2, ranges = deltas + segX2;
    for (let s = 0; s < segX2 / 2; s++) {
      const end = b.readUInt16BE(ends + s * 2), start = b.readUInt16BE(starts + s * 2);
      const delta = b.readInt16BE(deltas + s * 2), ro = b.readUInt16BE(ranges + s * 2);
      for (let c = start; c <= end && c !== 0xffff; c++) {
        let g = ro === 0 ? (c + delta) & 0xffff : b.readUInt16BE(ranges + s * 2 + ro + (c - start) * 2);
        if (ro !== 0 && g) g = (g + delta) & 0xffff;
        if (g && c >= 0x20) cps.add(c);
      }
    }
  }
  return String.fromCodePoint(...[...cps].sort((a, b) => a - b));
}
const FULL = fontCharacters(font);

async function subsetBase64(chars) {
  const out = await subsetFont(font, chars, { targetFormat: "woff2" });
  return Buffer.from(out).toString("base64");
}

const numeric = await subsetBase64(NUMERIC_CHARS);
const ascii = await subsetBase64(ASCII);
const full = await subsetBase64(FULL);

writeFileSync(
  "src/font-subsets.ts",
  `// AUTO-GENERATED by scripts/build-font-subsets.mjs. Do not edit by hand.
// Base64 WOFF2 subsets of AauxOffice-Bold for embedding in generated SVGs.
export const NUMERIC_CHARS = ${JSON.stringify(NUMERIC_CHARS)};
export const SUBSET_NUMERIC = ${JSON.stringify(numeric)};
export const SUBSET_ASCII = ${JSON.stringify(ascii)};
// Every character the font covers (${[...FULL].length}): ASCII, most of Latin-1, curly quotes, dashes.
export const FONT_CHARS = ${JSON.stringify(FULL)};
export const SUBSET_FULL = ${JSON.stringify(full)};
`,
);
console.log(`wrote src/font-subsets.ts (numeric=${numeric.length} ascii=${ascii.length} full=${full.length} b64 chars)`);
